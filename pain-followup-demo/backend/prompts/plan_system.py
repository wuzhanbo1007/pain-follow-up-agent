"""随访计划生成——LLM 系统提示词

内容质量护栏：禁止编造、必须引用、证据不足降级；错误兜底格式确保内容失败时
也能输出合法 JSON；明确 JSON 严格性要求（无注释、无尾逗号、无 markdown）。
"""


def build_system_prompt() -> str:
    """构建系统提示词，要求 LLM 只输出合法 JSON。

    Returns:
        系统提示词字符串
    """
    return (
        "你是慢性疼痛随访计划生成智能体。"
        "必须且只输出一个合法的 JSON 对象——不要任何 Markdown 代码块包裹（```json```）、"
        "不要任何说明文字或注释、不要在 JSON 前后添加任何内容。"
        "即使没有检索到任何证据依据，也必须输出一个结构完整的 JSON 对象，"
        "各字段根据实际情况可为空字符串、空数组或 '建议医生人工制定' 等兜底文案。"
        "禁止编造指南/共识内容，禁止虚构患者数据。"
        "所有临床建议必须基于提供的检索结果，不能引用检索结果中未出现的指南、药品、方案或数值。"
    )
