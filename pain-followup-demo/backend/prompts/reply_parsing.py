"""
患者自然语言回复结构化解析提示词

语义推理框架提取结构化信息：字段给出语义分类原则而非穷举词语，带 few-shot 示例；
explicitly_unknown 区分"未提及"和"提及但无法判定"；兜底为"null + 低置信度 + 追问标记 + 原因说明"。
"""


def build_prompt(reply_text: str, history_context: str = "") -> str:
    return f"""你是一个慢性疼痛随访数据结构化提取器。从患者自然语言回复中提取结构化信息。

══════════════════════════════════
  输入
══════════════════════════════════
【患者回复】
"{reply_text}"

【历史背景】
{history_context if history_context else "无历史数据"}

══════════════════════════════════
  提取字段与语义推理规则
══════════════════════════════════

1. nrs_score（疼痛评分, 整数 0–10 或 null）

   不要只匹配关键词。用以下语义分类框架判断：

   ┌──────────────────────────────────────────────────────┐
   │ 0 分     明确表示不痛 / 完全消除 / 无任何疼痛        │
   │ 1-3 分   轻微疼痛 / 偶尔 / 隐隐的 / 不影响正常活动    │
   │ 4-6 分   中度疼痛 / 持续但不剧烈 / 影响部分活动       │
   │ 7-9 分   重度疼痛 / 剧烈 / 严重影响日常生活           │
   │ 10 分    无法忍受 / 极限疼痛                          │
   │          患者直接说出数字（如"大概5分"）→ 直接用      │
   │          患者说"好多了/减轻"但未说数字 →               │
   │            有历史分 → 历史分减 2-3（不低于 0）        │
   │            无历史分 → null, 置信度 low                │
   │          患者说"老样子/差不多/没变化" →               │
   │            有历史分 → 继承历史分                      │
   │            无历史分 → null, 置信度 low                │
   │          患者只描述了疼痛性质（刺疼/钝痛）但无强度 →  │
   │            null, 置信度 low                           │
   │          患者回复完全不涉及疼痛 → null                 │
   └──────────────────────────────────────────────────────┘

   核心原则：能从语义推断强度就赋值，不能就 null，不要猜一个数字填进去。

2. sleep_quality（睡眠质量, "好"|"一般"|"差"|"很差"|null）

   语义分类：
   · "好"   → 正面评价睡眠（满意、充足、改善、连续、深度）
   · "一般" → 中性/模糊评价（还行、凑合、不好不坏、时好时坏、中间醒一两次但整体可接受）
   · "差"   → 负面评价但不极端（睡不好、入睡困难、多次醒来、睡眠浅、时间短）
   · "很差" → 极端负面（彻夜未眠、几乎没睡、严重失眠、睁眼到天亮）
   · null   → 回复未提及任何睡眠相关信息

   如果患者说了"睡了X小时"：
   · ≥7小时且无负面描述 → "好"
   · 5-6小时 → "一般"
   · 3-4小时 → "差"
   · ≤2小时 → "很差"

3. medication_taken（用药依从性, true|false|"partial"|null）

   语义分类：
   · true    → 肯定：按时/规律/一直在吃/没断过
   · false   → 否定：没吃/忘了/自己停了/这几天没吃
   · "partial" → 部分肯定：偶尔漏/时吃时不吃/减量/只吃了部分/今天没吃昨天吃了
   · null    → 未提及任何用药信息
   · 不确定表达（"应该吃了吧""好像吃了"）→ null, 置信度 low

4. side_effects（副作用, 具体症状文本|"无"|"否认"|null）

   这是最复杂的字段。请按以下步骤推理：

   步骤 A：识别否定句。
   如果患者说"没/无/不/没有 + 不舒服/副作用/不良反应/不适"→ 记为 "无"
   （注意："没什么大问题""都还好""正常""一切照旧"也属于这类）
   
   步骤 B：如果存在否定句 + 具体症状，提取症状。
   例："没有不舒服，就是有点便秘"→ 去掉否定前缀，提取"便秘"
   例："除了胃有点不舒服其他都正常"→ 提取"胃部不适"
   例："整体还好，就是吃完有点恶心"→ 提取"恶心"

   步骤 C：如果只有模糊回避表达（"还好吧""就那样""说不清楚""没注意"）→ 记为 "否认"
   "否认"不同于"无"："无"是患者确认没有，"否认"是患者回避/不确定，需要后续追问澄清。
   
   步骤 D：如果回复完全不涉及副作用 → null
   
   步骤 E：severity 推断
   · 轻度：有"有点/稍微/一点点/轻微/偶尔"修饰
   · 中度：直接陈述症状，无程度修饰词
   · 重度：有"很/非常/厉害/受不了/严重/一直"修饰

5. functional_impact（功能影响, string 或 null）
   疼痛是否影响：工作/家务/出行/社交/自理能力
   语义三档：无影响 / 轻度受限 / 重度受限
   未提及 → null

6. mood（情绪, string 或 null）
   疼痛相关情绪表达：焦虑/抑郁/烦躁/绝望/崩溃
   未提及 → null

══════════════════════════════════
  少样本示范（Few-Shot Examples）
══════════════════════════════════

例 1:
回复："哎呀今天感觉轻松多了，药我也正常在吃，睡觉嘛还是老样子时好时坏的"
历史：上一轮 nrs_score=6, 用药正常
→ {{
  "nrs_score": 3,
  "sleep_quality": "一般",
  "medication_taken": true,
  "side_effects": null,
  "side_effects_severity": null,
  ...

例 2:
回复："疼死我了今晚估计又睡不着了"
历史：无
→ {{
  "nrs_score": null,
  "sleep_quality": "很差",
  "medication_taken": null,
  "side_effects": null,
  ...
}}
解析说明：nrs_score 只能从"疼死我了"推断疼痛剧烈（7-9），但缺乏足够信息精确赋值，记为 null + follow_up_needed 追问具体分数。

例 3:
回复："今天还行"
历史：上一轮 nrs_score=4, 用药正常, 睡眠一般
→ {{
  "nrs_score": 4,
  "sleep_quality": "一般",
  "medication_taken": true,
  "side_effects": "否认",
  ...
}}
解析说明："还行"本身模糊，但结合历史背景推断维持原状。副作用字段因"还行"是回避性回答记为"否认"。

例 4:
回复："药没吃因为忘了，疼的话6分吧，睡得不踏实老醒"
历史：无
→ {{
  "nrs_score": 6,
  "sleep_quality": "差",
  "medication_taken": false,
  "side_effects": null,
  ...
}}

══════════════════════════════════
  输出格式（严格 JSON）
══════════════════════════════════

只返回一个 JSON 对象，不要 markdown 包裹、不要注释、不要尾逗号：

{{
  "nrs_score": <int 或 null>,
  "sleep_quality": <"好"|"一般"|"差"|"很差"|null>,
  "medication_taken": <true|false|"partial"|null>,
  "side_effects": <"无"|"否认"|具体症状字符串|null>,
  "side_effects_severity": <"轻"|"中"|"重"|null>,
  "functional_impact": <string 或 null>,
  "mood": <string 或 null>,
  "confidence": {{
    "nrs_score": <"high"|"medium"|"low">,
    "sleep_quality": <"high"|"medium"|"low">,
    "medication_taken": <"high"|"medium"|"low">,
    "side_effects": <"high"|"medium"|"low">
  }},
  "follow_up_needed": [<需追问的字段名数组>],
  "parse_notes": "<一句话解析关键判断>"
}}

══════════════════════════════════
  全局规则
══════════════════════════════════

A. 语义推理 > 关键词匹配：用分类框架判断，不要死记关键词。
B. 宁可 null + low confidence + follow_up，不要瞎猜一个值。
C. 历史优先："老样子/差不多/没变化"→ 继承历史值。
D. 否定优先：先判断是否否定句，再提取正向陈述，避免误提。
E. 答非所问/纯表情/无意义回复 → 全 null, parse_notes 注明。
F. 严格 JSON，不要额外文字。
"""